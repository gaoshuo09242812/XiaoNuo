"""Keep upstream WQY glyph bytes intact and rebuild only the Unicode index.

Format reference: U8g2 2.36.19 src/clib/u8g2_font.c,
u8g2_font_get_glyph_data (23-byte header, big-endian Unicode index).
"""
import argparse
import ast
import hashlib
import json
from pathlib import Path
import re

CAPTIONS='显示测试请说话准备中收音完成我在已停止识别思考回复联网连接校时'
NAME='u8g2_font_wqy12_t_gb2312a'


def extract(source):
    match=re.search(r'const uint8_t '+NAME+r'\[(\d+)\][^=]*=\s*((?:"(?:[^"\\]|\\.)*"\s*)+);',source)
    if not match:raise ValueError('Expected upstream WQY array not found')
    raw=b''.join(ast.literal_eval('b'+part) for part in re.findall(r'"(?:[^"\\]|\\.)*"',match[2]))+b'\0'
    if len(raw)!=int(match[1]):raise ValueError('Unexpected upstream array length')
    return raw


def glyph_record(raw,code):
    if code<=255:
        pos=23
        while raw[pos+1]:
            size=raw[pos+1]
            if raw[pos]==code:return raw[pos:pos+size]
            pos+=size
        return None
    start=23+int.from_bytes(raw[21:23],'big')
    pos=table=start
    while True:
        pos+=int.from_bytes(raw[table:table+2],'big')
        end=int.from_bytes(raw[table+2:table+4],'big');table+=4
        if end>=code:break
    while int.from_bytes(raw[pos:pos+2],'big'):
        size=raw[pos+2]
        if size<3:raise ValueError('Invalid glyph record')
        if int.from_bytes(raw[pos:pos+2],'big')==code:return raw[pos:pos+size]
        pos+=size
    return None


def generate(upstream,output):
    raw=extract(upstream.read_text(encoding='latin-1'))
    start=23+int.from_bytes(raw[21:23],'big')
    codes=sorted(set(map(ord,CAPTIONS)))
    records=[]
    for code in codes:
        record=glyph_record(raw,code)
        if record is None:raise ValueError(f'Missing glyph U+{code:04X}')
        records.append(record)
    # Keep ASCII offsets and bit encoding; one Unicode lookup block ends at FFFF.
    compact=bytearray(raw[:start]+b'\x00\x04\xff\xff'+b''.join(records)+b'\0\0')
    ascii_count=sum(glyph_record(raw,code) is not None for code in range(256))
    compact[0]=(ascii_count+len(codes))%256
    for code in list(range(256))+codes:
        assert glyph_record(compact,code)==glyph_record(raw,code),(code,'glyph changed')
    assert glyph_record(compact,0x9fff) is None
    lines=['#pragma once','#include <U8g2lib.h>',
        '// Generated by tools/subset_oled_font.py from upstream WenQuanYi 12px.',
        '// Preserve the upstream font license: https://github.com/olikraus/u8g2',
        '// Glyph encoding/bitmaps are copied unchanged; only the index is reduced.',
        f'const uint8_t xiaonuo_status_font[{len(compact)}] U8G2_FONT_SECTION("xiaonuo_status_font") = {{']
    lines += ['  '+','.join(f'0x{byte:02x}' for byte in compact[i:i+20])+',' for i in range(0,len(compact),20)]
    lines += ['};','']
    output.write_text('\n'.join(lines),encoding='utf-8')
    metadata={'upstream_font':NAME,'upstream_sha256':hashlib.sha256(raw).hexdigest(),
        'upstream_bytes':len(raw),'subset_bytes':len(compact),'captions':CAPTIONS,
        'all_original_ascii_preserved':True,'unicode_glyphs':len(codes),
        'glyph_records_identical':True,'subset_sha256':hashlib.sha256(compact).hexdigest()}
    output.with_suffix('.json').write_text(json.dumps(metadata,ensure_ascii=False,indent=2),encoding='utf-8')
    return metadata


if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('upstream',type=Path)
    parser.add_argument('--output',type=Path,default=Path(__file__).resolve().parents[1]/'firmware/XiaoNuo/status_font.h')
    args=parser.parse_args()
    print(json.dumps(generate(args.upstream,args.output),ensure_ascii=False))
