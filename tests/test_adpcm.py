class DecoderTests(unittest.TestCase):
    def test_reference_vectors_include_sign_and_saturation(self):
        for encoded, initial, expected, final in (
            ('078f', (0, 0), '00000b000900f0ff', (-16, 15)),
            ('00ff77', (32760, 88), 'ff7fff7f9eb90080fc6fff7f', (32767, 88)),
        ):
            pcm, state = decode(bytes.fromhex(encoded), *initial)
            self.assertEqual((pcm.hex(), state), (expected, final))

    def test_state_survives_frame_boundaries(self):
        data = bytes(range(256)) * 7
        expected, final = decode(data, -1234, 39)
        state = (-1234, 39)
        pieces = []
        for position in range(0, len(data), 17):
            pcm, state = decode(data[position:position + 17], *state)
            pieces.append(pcm)
        self.assertEqual((b''.join(pieces), state), (expected, final))

    def test_untrusted_states_and_sizes_are_bounded(self):
        for predictor, index in ((True, 0), (0, False), (32768, 0), (-32769, 0), (0, 89), (0, -1), (None, 0)):
            with self.assertRaises(XiaoNuoError):
                decode(b'\0', predictor, index)
        for data in (b'', b'\0' * (MAX_ENCODED_BYTES + 1), '00', None):
            with self.assertRaises(XiaoNuoError):
                decode(data)
        self.assertEqual(len(decode(b'\0' * MAX_ENCODED_BYTES)[0]), 192000)


class EncoderTests(unittest.TestCase):
    def test_independent_reference_vectors(self):
        for pcm, initial, expected, final in (
            ('00000b000900f0ff', (0, 0), '078f', (-16, 15)),
            ('3412cdab', (-32768, 88), '4b', (-24575, 87)),
        ):
            encoded, state = encode(bytes.fromhex(pcm), *initial)
            self.assertEqual((encoded.hex(), state), (expected, final))

    def test_encoder_length_state_and_bounds(self):
        pcm = bytes(range(256)) * 4
        encoded, state = encode(pcm, 1234, 39)
        self.assertEqual(len(encoded), (len(pcm) // 2 + 1) // 2)
        self.assertEqual(decode(encoded, 1234, 39)[1], state)
        for bad in (b'', b'\0', b'\0' * (MAX_PCM_BYTES + 2)):
            with self.assertRaises(XiaoNuoError):
                encode(bad)
        for predictor, index in ((True, 0), (0, 89)):
            with self.assertRaises(XiaoNuoError):
                encode(b'\0\0', predictor, index)


class CompressedReceiverTests(unittest.TestCase):
    def test_payload_length_hash_and_decoder_are_applied_to_distinct_domains(self):
        receiver = AudioReceiver(str(uuid4()), 2, encoding='ima_adpcm4')
        encoded = b'\x07\x8f' * 8000
        self.assertEqual(receiver.snapshot()['expected_bytes'], 16000)
        # Odd byte fragments are valid compressed packets.
        pieces = [encoded[:1]] + [encoded[i:i + 999] for i in range(1, len(encoded), 999)]
        for sequence, piece in enumerate(pieces):
            receiver.push(encode_audio_frame(receiver.stream_id, sequence, piece) if len(piece) % 2 == 0
                          else self.frame(receiver, sequence, piece))
        pcm = receiver.finish(hashlib.sha256(encoded).hexdigest())
        self.assertEqual(len(pcm), 64000)
        self.assertEqual(receiver.snapshot()['received_bytes'], 0)
        self.assertEqual(pcm[:8].hex(), '00000b000900f0ff')
        # Independently generated by audioop-lts 0.2.2.
        self.assertEqual(hashlib.sha256(pcm).hexdigest(), '4902ddb4abcaeff7b4f7b626a990deea59beed3f51b5d54cae23fd70f6723e07')

    @staticmethod
    def frame(receiver, sequence, data):
        from app.network_audio import HEADER, MAGIC
        return HEADER.pack(MAGIC, receiver.stream_id.bytes, sequence) + data

    def test_bad_hash_discards_encoded_audio_without_decoding(self):
        receiver = AudioReceiver(str(uuid4()), 2, encoding='ima_adpcm4')
        for sequence in range(16):
            receiver.push(encode_audio_frame(receiver.stream_id, sequence, b'\0' * 1000))
        with self.assertRaisesRegex(XiaoNuoError, 'NETWORK_AUDIO_CHECKSUM_MISMATCH'):
            receiver.finish('0' * 64)
        self.assertEqual(receiver.snapshot()['received_bytes'], 0)


class ProtocolFourTests(unittest.TestCase):
    def setUp(self):
        self.fixture = fixtures.NetworkUploadTests('test_authenticated_upload_reaches_handler_once_and_filters_response')
        self.fixture.setUp()
        self.addCleanup(self.fixture.doCleanups)

    def test_compressed_upload_is_decoded_before_the_existing_handler(self):
        fixture = self.fixture
        with fixture.connect() as socket:
            self.assertEqual(fixture.hello(socket, 4)['protocol'], 4)
            ready = fixture.begin(socket, encoding='ima_adpcm4', predictor=0, step_index=0)
            self.assertEqual((ready['format'], ready['expected_bytes']), ('ima_adpcm4', 16000))
            for sequence in range(16):
                socket.send_bytes(encode_audio_frame(ready['stream_id'], sequence, b'\0' * 1000))
            socket.send_json({'type': 'audio_end', 'stream_id': ready['stream_id'],
                              'sha256': hashlib.sha256(b'\0' * 16000).hexdigest()})
            self.assertEqual(socket.receive_json()['type'], 'audio_processing')
            self.assertEqual(socket.receive_json()['type'], 'audio_result')
        self.assertEqual(len(fixture.calls), 1)
        self.assertEqual(fixture.calls[0][0], b'\0' * 64000)

    def test_old_protocols_cannot_silently_change_encoding(self):
        for protocol in (2, 3):
            with self.fixture.connect() as socket:
                self.fixture.hello(socket, protocol)
                with self.assertRaises(WebSocketDisconnect):
                    self.fixture.begin(socket, encoding='ima_adpcm4', predictor=0, step_index=0)
        self.assertEqual(self.fixture.states(), [])

    def test_compressed_wake_keeps_existing_consent_and_no_reply_gate(self):
        received = []

        class Handler:
            wake_enabled = True

            async def wake_probe(self, pcm, *args):
                received.append(pcm)
                return {'transcript': '', 'reply_text': '', '_wake_status': 'ignored', '_followup_seconds': 0}

        fixture = self.fixture
        fixture.make_app(Handler())
        with fixture.connect() as socket:
            self.assertTrue(fixture.hello(socket, 4)['computer_wake_enabled'])
            ready = fixture.begin(socket, trigger='wake', consent='owner-computer-wake',
                                  encoding='ima_adpcm4', predictor=0, step_index=0)
            for sequence in range(16):
                socket.send_bytes(encode_audio_frame(ready['stream_id'], sequence, b'\0' * 1000))
            socket.send_json({'type': 'audio_end', 'stream_id': ready['stream_id'],
                              'sha256': hashlib.sha256(b'\0' * 16000).hexdigest()})
            self.assertEqual(socket.receive_json()['type'], 'audio_processing')
            result = socket.receive_json()
            self.assertEqual((result['type'], result['wake_status']), ('audio_result', 'ignored'))
            self.assertEqual((result['transcript'], result['reply_text']), ('', ''))
            self.assertFalse(result['reply_audio_enabled'])
        self.assertEqual(received, [b'\0' * 64000])

    def test_incomplete_codec_metadata_is_rejected_before_claim(self):
        with self.fixture.connect() as socket:
            self.fixture.hello(socket, 4)
            with self.assertRaises(WebSocketDisconnect):
                self.fixture.begin(socket, encoding='ima_adpcm4')
        self.assertEqual(self.fixture.states(), [])

    def test_malformed_state_and_unknown_fields_never_reach_handler(self):
        for changes in ({'predictor': True}, {'step_index': 89}, {'extra': 1}, {'encoding': 'unknown'}):
            with self.fixture.connect() as socket:
                self.fixture.hello(socket, 4)
                fields = dict(encoding='ima_adpcm4', predictor=0, step_index=0)
                fields.update(changes)
                with self.assertRaises(WebSocketDisconnect):
                    self.fixture.begin(socket, **fields)
        self.assertEqual(self.fixture.calls, [])
